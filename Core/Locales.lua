-- 构造最终语言表 L（按客户端 GetLocale 自动合并，缺失键自动回退至 L_enUS）
local activeTable = {}
for k, v in pairs(L_enUS) do
    activeTable[k] = v
end

if L_zhCN then
    for k, v in pairs(L_zhCN) do
        activeTable[k] = v
    end
end

if L_zhTW then
    for k, v in pairs(L_zhTW) do
        activeTable[k] = v
    end
end

-- 显式解引用闲置的多语言原始字典，促使垃圾回收器释放内存
L_zhCN = nil
L_zhTW = nil

ns.L = setmetatable(activeTable, {
    __index = function(_, key)
        return L_enUS[key] or tostring(key)
    end,
})

function ns.FormatBracket(text)
    return string.format(ns.L["BRACKET_FMT"], tostring(text or ""))
end
